import { generateKeyPairSync, createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";

/**
 * Generates a schema version 3 (whole-record) Execution Trust Record signed
 * by the server's own signing code (VerificationCrypto), for the verifier's
 * tests in parmana-verifier#27. Replaces hand-built v3 vectors.
 *
 * Usage:
 *   npx tsx scripts/generate-whole-record-v3-fixture.ts <out-dir>
 *
 * Writes <out-dir>/record.json (the signed record) and <out-dir>/trust.json
 * (the public keys the verifier pins). Uses ephemeral Ed25519 and ML-DSA-65
 * keys written only to <out-dir>; never touches PARMANA_KEY_DIR.
 *
 * Not a running server: this calls the same signing code the server calls,
 * with configuration set in this process.
 */

const [outDir] = process.argv.slice(2);

if (!outDir) {
  console.error("Usage: generate-whole-record-v3-fixture.ts <out-dir>");
  process.exit(2);
}

mkdirSync(outDir, { recursive: true });

const edKeyId = "whole-record-ed";
const mlKeyId = "whole-record-ml";

const ed = generateKeyPairSync("ed25519");
const ml = generateKeyPairSync("ml-dsa-65");

writeFileSync(
  `${outDir}/${edKeyId}.private.pem`,
  ed.privateKey.export({ format: "pem", type: "pkcs8" }),
);
writeFileSync(
  `${outDir}/${edKeyId}.public.pem`,
  ed.publicKey.export({ format: "pem", type: "spki" }),
);
writeFileSync(
  `${outDir}/${mlKeyId}.private.pem`,
  ml.privateKey.export({ format: "pem", type: "pkcs8" }),
);
writeFileSync(
  `${outDir}/${mlKeyId}.public.pem`,
  ml.publicKey.export({ format: "pem", type: "spki" }),
);

// Configuration the server reads from the environment, set before the
// signing modules load it.
process.env.PARMANA_KEY_DIR = outDir;
process.env.PARMANA_POLICY_DIR = outDir;
process.env.PARMANA_VERIFICATION_KEY_ID = edKeyId;
process.env.PARMANA_VERIFICATION_SECONDARY_KEY_ID = mlKeyId;
process.env.CRYPTO_MODE = "hybrid";
process.env.PRIMARY_SIGNATURE_PROVIDER = "ed25519";
process.env.SECONDARY_SIGNATURE_PROVIDER = "ml-dsa-65";
process.env.HYBRID_SCHEMA_VERSION = "3";
process.env.HYBRID_SCHEMA_V3_ACKNOWLEDGED = "true";

const { VerificationCrypto } = await import("@parmana/crypto");

const crypto = new VerificationCrypto();

const at = "2026-03-01T00:00:00.000Z";

const draft = {
  trustRecordId: "whole-record-v3-fixture",
  businessTransactionId: "whole-record-v3-fixture",
  transaction: {
    businessTransactionId: "whole-record-v3-fixture",
    status: "RECEIVED",
    createdAt: new Date(at),
    signals: { amount: 100 },
  },
  overrides: [],
  executions: [],
  createdAt: new Date(at),
  updatedAt: new Date(at),
  schemaVersion: 3,
} as never;

const trustRecordHash = await crypto.hash(draft);
const signature = await crypto.sign(draft);
const signatures = await crypto.signHybrid({
  ...draft,
  trustRecordHash,
  signature,
} as never);

const record = { ...draft, trustRecordHash, signature, signatures };

writeFileSync(`${outDir}/record.json`, JSON.stringify(record, null, 2));

const pubPem = (key: { publicKey: { export: (o: object) => unknown } }) =>
  String(key.publicKey.export({ format: "pem", type: "spki" }));
const fingerprint = (key: { publicKey: { export: (o: object) => Buffer } }) =>
  "sha256:" +
  createHash("sha256")
    .update(key.publicKey.export({ format: "der", type: "spki" }))
    .digest("hex");

const trust = {
  note: "Generated by scripts/generate-whole-record-v3-fixture.ts in parmana-core. Fixture keys, not production keys.",
  hybridRequiredFrom: "2026-01-01T00:00:00.000Z",
  keys: [
    {
      keyId: edKeyId,
      algorithm: "ed25519",
      publicKeyPem: pubPem(ed),
      fingerprint: fingerprint(ed),
      validFrom: "2000-01-01T00:00:00.000Z",
      validUntil: null,
      compromised: false,
    },
    {
      keyId: mlKeyId,
      algorithm: "dilithium3",
      publicKeyPem: pubPem(ml),
      fingerprint: fingerprint(ml),
      validFrom: "2000-01-01T00:00:00.000Z",
      validUntil: null,
      compromised: false,
    },
  ],
};

writeFileSync(`${outDir}/trust.json`, JSON.stringify(trust, null, 2));

console.log(
  `wrote ${outDir}/record.json and ${outDir}/trust.json (schemaVersion 3, ${signatures.length} hybrid entries)`,
);
