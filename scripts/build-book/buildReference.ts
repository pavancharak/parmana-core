interface ErrorEntry {
  readonly statuses: Set<string>;
  readonly operations: Set<string>;
  message: string;
}

/**
 * Every error class in the server source whose constructor calls
 * super("<CODE>", ..., <status>): the code and HTTP status it declares.
 */
function errorClasses(): Map<string, { status?: string; source: string }> {
  const found = new Map<
    string,
    { status?: string; source: string; className?: string }
  >();
  const classes = new Map<string, { parent?: string; status?: string }>();
  const roots = ["packages"];
  const files: string[] = [];

  const walk = (dir: string): void => {
    for (const entry of readdirSync(join(repoRoot, dir), {
      withFileTypes: true,
    })) {
      const path = `${dir}/${entry.name}`;

      if (entry.isDirectory()) {
        if (["node_modules", "dist", "tests", "test"].includes(entry.name))
          continue;
        walk(path);
      } else if (
        entry.name.endsWith(".ts") &&
        !entry.name.endsWith(".d.ts") &&
        path.includes("/src/")
      ) {
        files.push(path);
      }
    }
  };

  roots.forEach(walk);

  for (const path of files) {
    const text = read(path);
    if (!text.includes("super(") && !text.includes("code:")) continue;

    const source = ts.createSourceFile(
      path,
      text,
      ts.ScriptTarget.Latest,
      true,
    );

    const visit = (node: ts.Node): void => {
      if (ts.isClassDeclaration(node) && node.name !== undefined) {
        const parent = node.heritageClauses
          ?.find((h) => h.token === ts.SyntaxKind.ExtendsKeyword)
          ?.types[0]?.expression.getText(source);
        classes.set(node.name.text, {
          ...(parent !== undefined ? { parent } : {}),
          ...(classes.get(node.name.text)?.status !== undefined
            ? { status: classes.get(node.name.text)?.status }
            : {}),
        });
      }

      if (
        ts.isCallExpression(node) &&
        node.expression.kind === ts.SyntaxKind.SuperKeyword &&
        node.arguments.length >= 2
      ) {
        let owner: ts.Node | undefined = node.parent;
        while (owner !== undefined && !ts.isClassDeclaration(owner))
          owner = owner.parent;
        const ownerName =
          owner !== undefined && ts.isClassDeclaration(owner)
            ? owner.name?.text
            : undefined;
        const numeric = node.arguments.find((a): a is ts.NumericLiteral =>
          ts.isNumericLiteral(a),
        );
        if (ownerName !== undefined && numeric !== undefined) {
          classes.set(ownerName, {
            ...classes.get(ownerName),
            status: numeric.text,
          });
        }

        // ParmanaError subclasses pass the code first; RuntimeError
        // subclasses pass (message, status, code). Take whichever argument
        // is a literal in the form of a code.
        const code = node.arguments
          .map((argument) =>
            ts.isStringLiteral(argument) ||
            ts.isNoSubstitutionTemplateLiteral(argument)
              ? argument.text
              : undefined,
          )
          .find(
            (text) =>
              text !== undefined &&
              /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$/.test(text),
          );

        if (
          code !== undefined &&
          /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$/.test(code)
        ) {
          const status = node.arguments
            .slice(1)
            .find((a): a is ts.NumericLiteral => ts.isNumericLiteral(a));

          if (!found.has(code)) {
            found.set(code, {
              ...(status !== undefined ? { status: status.text } : {}),
              source: path,
              ...(ownerName !== undefined ? { className: ownerName } : {}),
            });
          }
        }
      }

      // A route answering inline: res.status(<N>).json({ ..., code: "<CODE>" }),
      // where code and status may each be `condition ? a : b`, paired in order.
      if (
        ts.isPropertyAssignment(node) &&
        ts.isIdentifier(node.name) &&
        node.name.text === "code"
      ) {
        const literal = (e: ts.Expression): string | undefined =>
          (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e)) &&
          /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$/.test(e.text)
            ? e.text
            : undefined;
        const codes = ts.isConditionalExpression(node.initializer)
          ? [
              literal(node.initializer.whenTrue),
              literal(node.initializer.whenFalse),
            ]
          : [literal(node.initializer)];

        let parent: ts.Node | undefined = node.parent;
        let statuses: Array<string | undefined> = [];

        while (parent !== undefined && !ts.isStatement(parent)) {
          if (
            ts.isCallExpression(parent) &&
            ts.isPropertyAccessExpression(parent.expression) &&
            parent.expression.name.text === "json" &&
            ts.isCallExpression(parent.expression.expression) &&
            ts.isPropertyAccessExpression(
              parent.expression.expression.expression,
            ) &&
            parent.expression.expression.expression.name.text === "status"
          ) {
            const argument = parent.expression.expression.arguments[0];
            const numeric = (e: ts.Expression): string | undefined =>
              ts.isNumericLiteral(e) ? e.text : undefined;
            if (argument !== undefined) {
              statuses = ts.isConditionalExpression(argument)
                ? [numeric(argument.whenTrue), numeric(argument.whenFalse)]
                : [numeric(argument)];
            }
            break;
          }
          parent = parent.parent;
        }

        codes.forEach((code, i) => {
          const status = statuses.length === 1 ? statuses[0] : statuses[i];
          if (code !== undefined && status !== undefined && !found.has(code)) {
            found.set(code, { status, source: path });
          }
        });
      }

      ts.forEachChild(node, visit);
    };

    visit(source);
  }

  for (const entry of found.values()) {
    let name = entry.className;
    const seen = new Set<string>();

    while (
      entry.status === undefined &&
      name !== undefined &&
      !seen.has(name)
    ) {
      seen.add(name);
      const info = classes.get(name);
      if (info?.status !== undefined && name !== entry.className)
        entry.status = info.status;
      name = info?.parent;
    }
  }

  return found;
}

interface ErrorEntry {
  readonly statuses: Set<string>;
  readonly operations: Set<string>;
  message: string;
  source: string;
}

function errorsChapter(): GeneratedChapter {
  const spec = parse(read("openapi/openapi.bundled.yaml")) as {
    paths: Record<
      string,
      Record<
        string,
        { operationId?: string; responses?: Record<string, unknown> }
      >
    >;
  };
  const errors = new Map<string, ErrorEntry>();
  const entryFor = (code: string): ErrorEntry => {
    const existing = errors.get(code);
    if (existing !== undefined) return existing;
    const created: ErrorEntry = {
      statuses: new Set(),
      operations: new Set(),
      message: "",
      source: "",
    };
    errors.set(code, created);
    return created;
  };

  // 1. Every code in a real captured response.
  for (const operations of Object.values(spec.paths)) {
    for (const operation of Object.values(operations)) {
      if (
        operation?.operationId === undefined ||
        operation.responses === undefined
      )
        continue;

      for (const [status, response] of Object.entries(operation.responses)) {
        const examples =
          (
            response as {
              content?: Record<
                string,
                { examples?: Record<string, { value?: unknown }> }
              >;
            }
          ).content?.["application/json"]?.examples ?? {};

        for (const example of Object.values(examples)) {
          const value = example?.value as
            { code?: unknown; error?: unknown } | undefined;

          if (
            value === undefined ||
            typeof value.code !== "string" ||
            !/^[A-Z][A-Z0-9_]+$/.test(value.code)
          ) {
            continue;
          }

          const entry = entryFor(value.code);
          entry.statuses.add(status);
          entry.operations.add(operation.operationId);
          if (entry.message === "" && typeof value.error === "string")
            entry.message = value.error;
        }
      }
    }
  }

  // 2. Every error class in the server source.
  for (const [code, declared] of errorClasses()) {
    const entry = entryFor(code);
    if (declared.status !== undefined) entry.statuses.add(declared.status);
    entry.source = declared.source;
  }

  // 3. Where a known code is named in a response description.
  const known = new Set(errors.keys());

  for (const operations of Object.values(spec.paths)) {
    for (const operation of Object.values(operations)) {
      if (
        operation?.operationId === undefined ||
        operation.responses === undefined
      )
        continue;

      for (const [status, response] of Object.entries(operation.responses)) {
        const description = (response as { description?: unknown }).description;
        if (typeof description !== "string") continue;

        for (const match of description.matchAll(
          /\b[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+\b/g,
        )) {
          if (!known.has(match[0])) continue;
          const entry = entryFor(match[0]);
          entry.statuses.add(status);
          entry.operations.add(operation.operationId);
        }
      }
    }
  }

  const sorted = [...errors.entries()].sort(([a], [b]) => a.localeCompare(b));

  const lines = [
    frontMatter(
      "Reference: every error code",
      "Every error code the server can return, with its HTTP status, where it occurs and a real message, generated from the source and the OpenAPI file.",
    ),
    HEADER_NOTE,
    "",
    `Every error code the server declares, ${sorted.length} in all: each error class in \`packages/*/src\` (its code and HTTP status), and each \`code\` in a real captured response in \`openapi/openapi.bundled.yaml\`. An error body is \`{ "error": "<message>", "code": "<CODE>" }\`; a few refusals carry more fields, shown on the operation's page. "Returned by" lists the operations whose documented responses name the code; an empty cell means the code can be returned by any operation that reaches that part of the server. What to do for each class of error: [Errors and troubleshooting](/build-book/09-errors-and-troubleshooting).`,
    "",
    "| Code | HTTP | Returned by | Example message | Declared in |",
    "| ---- | ---- | ----------- | --------------- | ----------- |",
    ...sorted.map(
      ([code, entry]) =>
        `| \`${code}\` | ${[...entry.statuses].sort().join(", ")} | ${[
          ...entry.operations,
        ]
          .sort()
          .map((o) => `\`${o}\``)
          .join(
            ", ",
          )} | ${cell(entry.message)} | ${entry.source === "" ? "" : `\`${entry.source}\``} |`,
    ),
    "",
  ];

  return {
    file: `${BUILD_BOOK_DIRECTORY}/reference-errors.mdx`,
    content: lines.join("\n"),
  };
}

export function buildReferenceChapters(): GeneratedChapter[] {
  return [endpointsChapter(), sdkChapter(), errorsChapter()];
}
