interface SdkEntry {
  readonly signature: string;
  readonly summary: string;
}

function firstParagraph(text: string): string {
  const paragraph = text.trim().split(/\n\s*\n/)[0] ?? "";
  return cell(paragraph);
}

function typescriptClientMethods(): SdkEntry[] {
  const path = "typescript/src/client/ParmanaClient.ts";
  const source = ts.createSourceFile(
    path,
    read(path),
    ts.ScriptTarget.Latest,
    true,
  );
  const entries: SdkEntry[] = [];

  source.forEachChild((node) => {
    if (!ts.isClassDeclaration(node) || node.name?.text !== "ParmanaClient")
      return;

    for (const member of node.members) {
      if (!ts.isMethodDeclaration(member) || !ts.isIdentifier(member.name))
        continue;

      const modifiers = ts.getModifiers(member) ?? [];
      if (
        modifiers.some(
          (m) =>
            m.kind === ts.SyntaxKind.PrivateKeyword ||
            m.kind === ts.SyntaxKind.ProtectedKeyword,
        )
      ) {
        continue;
      }

      const parameters = member.parameters
        .map((p) => p.getText(source).replace(/\s+/g, " "))
        .join(", ");
      const returns = member.type
        ? `: ${member.type.getText(source).replace(/\s+/g, " ")}`
        : "";
      const doc = ts
        .getJSDocCommentsAndTags(member)
        .map((d) => (typeof d.comment === "string" ? d.comment : ""))
        .join("\n");

      entries.push({
        signature: `${member.name.text}(${parameters})${returns}`,
        summary: firstParagraph(doc),
      });
    }
  });

  return entries;
}

function typescriptExportedFunctions(): SdkEntry[] {
  const index = read("typescript/src/index.ts");
  const exported = new Set(
    [...index.matchAll(/^\s+([a-z][A-Za-z0-9]*),?$/gm)].map((m) => m[1] ?? ""),
  );
  const entries: SdkEntry[] = [];

  for (const path of [
    "typescript/src/crypto/offline-verifier.ts",
    "typescript/src/crypto/step-up.ts",
    "typescript/src/crypto/approval.ts",
    "typescript/src/crypto/release.ts",
    "typescript/src/crypto/canonical.ts",
  ]) {
    const source = ts.createSourceFile(
      path,
      read(path),
      ts.ScriptTarget.Latest,
      true,
    );

    source.forEachChild((node) => {
      if (!ts.isFunctionDeclaration(node) || node.name === undefined) return;
      if (
        !(ts.getModifiers(node) ?? []).some(
          (m) => m.kind === ts.SyntaxKind.ExportKeyword,
        )
      )
        return;
      if (!exported.has(node.name.text)) return;

      const parameters = node.parameters
        .map((p) => p.getText(source).replace(/\s+/g, " "))
        .join(", ");
      const returns = node.type
        ? `: ${node.type.getText(source).replace(/\s+/g, " ")}`
        : "";
      const doc = ts
        .getJSDocCommentsAndTags(node)
        .map((d) => (typeof d.comment === "string" ? d.comment : ""))
        .join("\n");

      entries.push({
        signature: `${node.name.text}(${parameters})${returns}`,
        summary: firstParagraph(doc),
      });
    });
  }

  return entries;
}

function pythonFunctions(
  path: string,
  indent: string,
  only?: ReadonlySet<string>,
): SdkEntry[] {
  const text = read(path);
  const pattern = new RegExp(
    `^${indent}def ([a-z][a-z0-9_]*)\\(([\\s\\S]*?)\\)(\\s*->\\s*[^:]+)?:\\n\\s*"""([\\s\\S]*?)"""`,
    "gm",
  );
  const entries: SdkEntry[] = [];

  for (const match of text.matchAll(pattern)) {
    const name = match[1] ?? "";
    if (only !== undefined && !only.has(name)) continue;

    const parameters = (match[2] ?? "")
      .split(",")
      .map((p) => p.replace(/\s+/g, " ").trim())
      .filter((p) => p !== "" && p !== "self")
      .join(", ");
    const returns = (match[3] ?? "").replace(/\s+/g, " ").trim();

    entries.push({
      signature: `${name}(${parameters})${returns === "" ? "" : ` ${returns}`}`,
      summary: firstParagraph((match[4] ?? "").replace(/``/g, "`")),
    });
  }

  return entries;
}

function pythonExportedFunctions(): SdkEntry[] {
  const init = read("python/parmana/crypto/__init__.py");
  const exported = new Set(
    [...init.matchAll(/"([a-z][a-z0-9_]*)"/g)].map((m) => m[1] ?? ""),
  );

  return [
    "python/parmana/crypto/offline_verifier.py",
    "python/parmana/crypto/step_up.py",
    "python/parmana/crypto/approval.py",
    "python/parmana/crypto/release.py",
    "python/parmana/crypto/canonical.py",
  ].flatMap((path) => pythonFunctions(path, "", exported));
}

function sdkTable(entries: readonly SdkEntry[]): string[] {
  return [
    "| Signature | What it does |",
    "| --------- | ------------ |",
    ...entries.map(
      (entry) => `| \`${cell(entry.signature)}\` | ${entry.summary || " "} |`,
    ),
    "",
  ];
}

function sdkChapter(): GeneratedChapter {
  const tsMethods = typescriptClientMethods();
  const pyMethods = pythonFunctions("python/parmana/client.py", "    ");

  const lines = [
    frontMatter(
      "Reference: every SDK method",
      "Every method of ParmanaClient in the TypeScript and Python SDKs, and every signing and verifying function they export, generated from the SDK source.",
    ),
    HEADER_NOTE,
    "",
    "Read from the SDK source with each method's own doc comment: `typescript/src/client/ParmanaClient.ts` and `python/parmana/client.py`. A method added to either client appears here the next time the reference is generated, and a test fails until it is. Configuration, retries and errors: [TypeScript](/sdks/typescript-configuration) and [Python](/sdks/python-configuration).",
    "",
    "## TypeScript: `ParmanaClient` (`@parmana/sdk`)",
    "",
    ...sdkTable(tsMethods),
    "## TypeScript: functions exported next to the client",
    "",
    "They make no request.",
    "",
    ...sdkTable(typescriptExportedFunctions()),
    "## Python: `ParmanaClient` (`parmana`)",
    "",
    ...sdkTable(pyMethods),
    "## Python: functions in `parmana.crypto`",
    "",
    'They make no request. Install with `pip install "parmana[verify]"`.',
    "",
    ...sdkTable(pythonExportedFunctions()),
  ];

  return {
    file: `${BUILD_BOOK_DIRECTORY}/reference-sdk.mdx`,
    content: lines.join("\n"),
  };
}

