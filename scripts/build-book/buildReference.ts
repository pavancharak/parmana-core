import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import ts from "typescript";
import { parse } from "yaml";

import { buildEndpointPages } from "../endpoints/buildEndpointPages.js";

/**
 * The generated reference chapters of the book "Build with Parmana"
 * (docs/site/build-book): every endpoint, every SDK method in both
 * languages, and every error code, read from the code itself, so they
 * cannot drift from it. tests/architecture/build-book-reference-up-to-date.test.ts
 * fails when a committed chapter differs from what this builds.
 *
 * Sources:
 * - endpoints: openapi/openapi.bundled.yaml, through buildEndpointPages,
 *   the same reading that makes the REST API pages;
 * - SDK methods: typescript/src/client/ParmanaClient.ts (TypeScript
 *   compiler API) and python/parmana/client.py, with each method's own
 *   doc comment, plus the functions each SDK exports for signing and
 *   verifying;
 * - error codes: every `code` in a response example of the OpenAPI file,
 *   each a real captured response, with its HTTP status.
 */

const repoRoot = dirname(dirname(dirname(fileURLToPath(import.meta.url))));

export const BUILD_BOOK_DIRECTORY = "docs/site/build-book";

export interface GeneratedChapter {
  readonly file: string;
  readonly content: string;
}

const HEADER_NOTE =
  "{/* Generated by scripts/generate-build-book-reference.ts. Do not edit: run `npm run generate:build-book-reference`. */}";

function read(path: string): string {
  return readFileSync(join(repoRoot, path), "utf8");
}

function cell(text: string): string {
  return text
    .replace(/\s+/g, " ")
    .replace(/\\/g, "\\\\")
    .replace(/\|/g, "\\|")
    .trim();
}

function frontMatter(title: string, description: string): string {
  return [
    "---",
    `title: "${title}"`,
    `description: "${description}"`,
    "---",
    "",
  ].join("\n");
}

