function endpointsChapter(): GeneratedChapter {
  const pages = buildEndpointPages();
  const groups = new Map<string, typeof pages>();

  for (const page of pages) {
    groups.set(page.group, [...(groups.get(page.group) ?? []), page]);
  }

  const lines = [
    frontMatter(
      "Reference: every endpoint",
      "Every operation of the Parmana REST API, grouped as in the API reference, generated from the OpenAPI file.",
    ),
    HEADER_NOTE,
    "",
    `Every operation the server exposes, ${pages.length} in all, read from \`openapi/openapi.bundled.yaml\`. Tests keep that file equal to the routes the server actually mounts (\`openapi-route-parity.test.ts\`). Each row links to the operation's page, with its schemas and real captured responses.`,
    "",
  ];

  for (const [group, entries] of groups) {
    lines.push(
      `## ${group}`,
      "",
      "| Method | Path | What it does |",
      "| ------ | ---- | ------------ |",
    );

    for (const entry of entries) {
      lines.push(
        `| \`${entry.method}\` | [\`${cell(entry.path)}\`](/${entry.navPath}) | ${cell(entry.description)} |`,
      );
    }

    lines.push("");
  }

  return {
    file: `${BUILD_BOOK_DIRECTORY}/reference-endpoints.mdx`,
    content: lines.join("\n"),
  };
}

