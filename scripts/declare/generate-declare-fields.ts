/**
 * Generates the field tables of the declare stage from the TypeScript types
 * that define a Business Transaction. The output lists each field's name,
 * type and whether it is required. "Set by" and "Meaning" cannot be read from
 * the types, so they stay in the hand-written document.
 *
 * Usage:
 *   tsx scripts/declare/generate-declare-fields.ts            write the file
 *   tsx scripts/declare/generate-declare-fields.ts --check    fail if the file differs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import ts from "typescript";

const ROOT = path.resolve(import.meta.dirname, "../..");
const OUT = path.join(ROOT, "docs/DECLARE_FIELDS.generated.md");

const SOURCES: Array<{ file: string; interfaces: string[] }> = [
  {
    file: "packages/shared/src/domain/business-transaction.ts",
    interfaces: ["BusinessTransaction"],
  },
  {
    file: "packages/shared/src/domain/metadata.ts",
    interfaces: ["TransactionMetadata"],
  },
  {
    file: "packages/shared/src/domain/authority.ts",
    interfaces: ["Authority"],
  },
  {
    file: "packages/shared/src/domain/authorization.ts",
    interfaces: ["Authorization"],
  },
  { file: "packages/shared/src/domain/intent.ts", interfaces: ["Intent"] },
  {
    file: "packages/shared/src/domain/policy-reference.ts",
    interfaces: ["PolicyReference"],
  },
];

interface FieldRow {
  name: string;
  type: string;
  required: boolean;
}

function readInterface(file: string, name: string): FieldRow[] {
  const full = path.join(ROOT, file);
  const source = ts.createSourceFile(
    full,
    readFileSync(full, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  let rows: FieldRow[] | undefined;
  source.forEachChild((node) => {
    if (ts.isInterfaceDeclaration(node) && node.name.text === name) {
      rows = node.members.filter(ts.isPropertySignature).map((member) => ({
        name: member.name.getText(source),
        type: member.type ? member.type.getText(source) : "unknown",
        required: member.questionToken === undefined,
      }));
    }
  });
  if (rows === undefined) {
    throw new Error(`interface ${name} not found in ${file}`);
  }
  return rows;
}

function render(): string {
  const lines: string[] = [
    "<!-- Generated by scripts/declare/generate-declare-fields.ts. Do not edit by hand. -->",
    "",
    "# Declare: generated field tables",
    "",
    "Read from the TypeScript types. A field is required when it has no `?`.",
    "",
  ];
  for (const { file, interfaces } of SOURCES) {
    for (const name of interfaces) {
      lines.push(
        `## ${name}`,
        "",
        `Source: \`${file}\``,
        "",
        "| Field | Type | Required |",
        "| --- | --- | --- |",
      );
      for (const row of readInterface(file, name)) {
        lines.push(
          `| \`${row.name}\` | \`${row.type.replace(/\|/g, "\\|")}\` | ${row.required ? "Yes" : "No"} |`,
        );
      }
      lines.push("");
    }
  }
  return lines.join("\n");
}

const output = render() + "\n";
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    current = "";
  }
  if (current !== output) {
    console.error(
      `${path.relative(ROOT, OUT)} is out of date. Run: tsx scripts/declare/generate-declare-fields.ts`,
    );
    process.exit(1);
  }
  console.log(`${path.relative(ROOT, OUT)} is up to date.`);
} else {
  writeFileSync(OUT, output, "utf8");
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
